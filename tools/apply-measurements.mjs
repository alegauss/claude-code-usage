#!/usr/bin/env node
/*
 * apply-measurements.mjs — fold a measurement run back into index.html.
 *
 * index.html is the artifact and there is no build step, so the page cannot
 * fetch a JSON file at runtime: a fetch would break opening the file directly,
 * and the raw measurements name real projects. Instead the measured numbers are
 * written into the page as one inline snapshot object, and the model reads its
 * coefficients from there. The page stays a single self-contained file.
 *
 *   npm run measure:json      # produce .usage/facts.json
 *   npm run apply             # fold it into index.html
 *
 * Only aggregates are copied in. Project names, prompts and per-project spend
 * stay in .usage/, which is gitignored.
 */

import { readFileSync, writeFileSync } from "node:fs";

const FACTS = process.argv[2] || ".usage/facts.json";
const PAGE = process.argv[3] || "index.html";

const START = "  /* ==== measured snapshot: generated by tools/apply-measurements.mjs — do not hand-edit ==== */";
const END = "  /* ==== end measured snapshot ==== */";

let facts;
try {
  facts = JSON.parse(readFileSync(FACTS, "utf8"));
} catch (err) {
  console.error(`cannot read ${FACTS} — run "npm run measure:json" first`);
  console.error(String(err.message || err));
  process.exit(1);
}

const round = (n, d = 2) => +Number(n || 0).toFixed(d);

/* Solo tasks are what the effort ladder describes; fan-out has its own row. */
const effortOf = level => {
  const c = facts.calibration?.[level]?.solo;
  if (!c) return null;
  return {
    calls: c.callsPerTask.median,
    out: c.outPerCall,
    ctxK: Math.round(c.ctxKPerCall),
    tasks: c.tasks
  };
};

/* The coordinator and agent shares vary by effort; take the level with the most
   fan-out tasks behind it rather than averaging across thin samples. "unset" is
   skipped — those are pre-effort-field sessions on an older model, so they
   describe a different agent than the one the page simulates. */
function shares() {
  let best = null;
  for (const [level, c] of Object.entries(facts.calibration || {})) {
    if (level === "unset") continue;
    if (!c.fanOut || c.coordShare == null || c.agentShare == null) continue;
    if (!best || c.fanOut.tasks > best.fanOut.tasks) best = c;
  }
  return best
    ? { coordShare: round(best.coordShare), agentShare: round(best.agentShare) }
    : { coordShare: 1.5, agentShare: 0.6 };
}

const loop = (facts.taskTypes?.topCommands || []).find(c => c.command === "/loop");
const t = facts.totals;

const snapshot = {
  generated: facts.generated.slice(0, 10),
  tasks: t.tasks,
  requests: t.requests,
  activeDays: t.activeDays,
  projects: t.projects,
  cost: Math.round(t.cost),
  costPerTask: {
    median: round(t.costPerTaskMedian),
    mean: round(t.costPerTaskMean),
    p90: round(t.costPerTaskP90)
  },
  cacheFactor: round(facts.cache.cacheFactor, 4),
  readPct: facts.cache.readPct,
  write1hPct: facts.cache.write1hPct,
  ctxKPerCall: Math.round(
    facts.projects.reduce((s, p) => s + p.ctxKPerCall * p.requests, 0) / t.requests
  ),
  effort: Object.fromEntries(
    ["high", "xhigh"].map(l => [l, effortOf(l)]).filter(([, v]) => v)
  ),
  ...shares(),
  fanOut: {
    requestPct: round(100 * t.subagentRequests / t.requests, 1),
    taskPct: round(100 * t.fanOutTasks / t.tasks, 1),
    subagentRequests: t.subagentRequests,
    workflows: facts.workflows.count,
    agentsPerWorkflow: facts.workflows.agentsPerWorkflowMedian,
    callsPerAgent: Math.round(facts.workflows.callsPerAgentMedian),
    costPerWorkflow: round(facts.workflows.costPerWorkflowMedian)
  },
  loop: loop
    ? { runs: loop.tasks, costMedian: round(loop.costPerTask), spendPct: round(100 * loop.cost / t.cost, 0) }
    : null,
  /* Use-case profiles carry no project names — see profiles() in measure-usage.mjs. */
  profiles: (facts.profiles || []).map(p => ({
    id: p.id, label: p.label, hint: p.hint,
    ctxK: p.ctxK, ctxKRange: p.ctxKRange,
    callsPerTask: p.callsPerTask, outPerCall: p.outPerCall,
    costPerTask: round(p.costPerTask), tasks: p.tasks, projects: p.projects
  }))
};

if (!snapshot.effort.high) {
  console.error("no solo tasks at effort=high in this measurement — refusing to write a snapshot");
  console.error("the page's effort ladder is anchored on high; widen the window and re-measure");
  process.exit(1);
}

/* Render the object the way the page already reads it, so a diff of index.html
   shows only the numbers that moved. */
const j = v => JSON.stringify(v);
const body = [
  START,
  "  var MEASURED = {",
  `    generated: ${j(snapshot.generated)},`,
  `    tasks: ${snapshot.tasks}, requests: ${snapshot.requests}, activeDays: ${snapshot.activeDays}, projects: ${snapshot.projects}, cost: ${snapshot.cost},`,
  `    costPerTask: { median: ${snapshot.costPerTask.median}, mean: ${snapshot.costPerTask.mean}, p90: ${snapshot.costPerTask.p90} },`,
  `    cacheFactor: ${snapshot.cacheFactor}, readPct: ${snapshot.readPct}, write1hPct: ${snapshot.write1hPct},`,
  `    ctxKPerCall: ${snapshot.ctxKPerCall},`,
  "    effort: {",
  ...Object.entries(snapshot.effort).map(([k, v], i, a) =>
    `      ${k.padEnd(5)}: { calls: ${v.calls}, out: ${v.out}, ctxK: ${v.ctxK}, tasks: ${v.tasks} }${i < a.length - 1 ? "," : ""}`),
  "    },",
  `    coordShare: ${snapshot.coordShare.toFixed(2)}, agentShare: ${snapshot.agentShare.toFixed(2)},`,
  "    fanOut: {",
  `      requestPct: ${snapshot.fanOut.requestPct}, taskPct: ${snapshot.fanOut.taskPct}, subagentRequests: ${snapshot.fanOut.subagentRequests},`,
  `      workflows: ${snapshot.fanOut.workflows}, agentsPerWorkflow: ${snapshot.fanOut.agentsPerWorkflow}, callsPerAgent: ${snapshot.fanOut.callsPerAgent}, costPerWorkflow: ${snapshot.fanOut.costPerWorkflow}`,
  "    },",
  `    loop: ${snapshot.loop ? `{ runs: ${snapshot.loop.runs}, costMedian: ${snapshot.loop.costMedian}, spendPct: ${snapshot.loop.spendPct} }` : "null"},`,
  "    profiles: [",
  ...snapshot.profiles.map((p, i, a) =>
    `      { id: ${j(p.id)}, label: ${j(p.label)}, hint: ${j(p.hint)}, ctxK: ${p.ctxK}, ` +
    `ctxKRange: [${p.ctxKRange[0]}, ${p.ctxKRange[1]}], callsPerTask: ${p.callsPerTask}, ` +
    `outPerCall: ${p.outPerCall}, costPerTask: ${p.costPerTask}, tasks: ${p.tasks}, projects: ${p.projects} }` +
    (i < a.length - 1 ? "," : "")),
  "    ]",
  "  };",
  END
].join("\n");

const page = readFileSync(PAGE, "utf8");
const from = page.indexOf(START);
const to = page.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  console.error(`snapshot markers not found in ${PAGE}`);
  console.error("expected a block delimited by:");
  console.error(`  ${START.trim()}`);
  console.error(`  ${END.trim()}`);
  process.exit(1);
}

const next = page.slice(0, from) + body + page.slice(to + END.length);
if (next === page) {
  console.log("index.html already matches the measurements — nothing to do");
  process.exit(0);
}
writeFileSync(PAGE, next);

console.log(`updated ${PAGE} from ${FACTS}`);
console.log(`  ${snapshot.tasks} tasks, ${snapshot.requests} requests, $${snapshot.cost} over ${snapshot.activeDays} active days`);
console.log(`  cache_factor ${snapshot.cacheFactor}, high = ${snapshot.effort.high.calls} calls x ${snapshot.effort.high.out} out`);
console.log(`  coordinator ${snapshot.coordShare.toFixed(2)}, agent ${snapshot.agentShare.toFixed(2)}`);
console.log("");
console.log("prose on slide 9 quotes these figures — reread it before committing");
